#!/usr/bin/env bash
# Shared defaults for local running experiments (Bash on Linux/WSL).
EXPERIMENT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MICRODUCK_REPO_ROOT="$(cd "$EXPERIMENT_DIR/../.." && pwd)"
export UV_PROJECT_ENVIRONMENT="${UV_PROJECT_ENVIRONMENT:-$MICRODUCK_REPO_ROOT/.venv}"
export MICRODUCK_ARTIFACTS="${MICRODUCK_ARTIFACTS:-$MICRODUCK_REPO_ROOT/artifacts}"
# Relative artifact paths are rooted in this checkout, regardless of caller cwd.
if [[ "$MICRODUCK_ARTIFACTS" != /* ]]; then
  export MICRODUCK_ARTIFACTS="$MICRODUCK_REPO_ROOT/$MICRODUCK_ARTIFACTS"
fi
export OMP_NUM_THREADS=4
export MKL_NUM_THREADS=4
export WANDB_MODE=offline
export PYTHONUNBUFFERED=1
export MICRODUCK_RUNNING_TARGET_MAX_SPEED=2.2
export MICRODUCK_RUNNING_SPEED_CAP=2.4
export MICRODUCK_RUNNING_HIGH_SPEED_STAGE_INTERVAL=750
export MICRODUCK_RUNNING_ACTION_RATE_WEIGHT=-0.10
export MICRODUCK_RUNNING_FORWARD_PROGRESS_WEIGHT=5.0
export MICRODUCK_RUNNING_ROBUST_PUSH_MPS=0.10
export MICRODUCK_RUNNING_ROBUST_TRUNK_COM_M=0.008
export MICRODUCK_RUNNING_ROBUST_HEAD_COM_M=0.006
export MICRODUCK_RUNNING_ROBUST_INITIAL_TILT_DEG=2.0
